/**
 * Light-basemap thumbnails for the `/cities` index cards.
 *
 * Each card ships a server-rendered fallback (USGS Topo `<img>` mosaic plus
 * category-coloured dots) for crawlers, no-JS visitors and first paint. A tiny
 * module script (`/cities-thumbs.js`, emitted by the generator because the CSP
 * forbids inline scripts) lazily swaps each card for a non-interactive
 * MapLibre map on the Light basemap (OpenFreeMap "positron"). MapLibre itself
 * is this repo's own hashed `dist/assets/maplibre-gl-*.js` chunk — never a CDN.
 *
 * Pure string/array helpers except `findMaplibreChunk`, which lists a directory.
 */

import { readdirSync } from 'node:fs'
import { CATEGORY_COLOR } from '../../../shared/categorySlugs.ts'

/** Same amber fallback the dots use for an unknown category. */
const DEFAULT_PIN_COLOR = '#f59e0b'

/** Light basemap — OpenFreeMap "positron" (free, keyless; see docs/basemaps.md). */
export const THUMB_STYLE_URL = 'https://tiles.openfreemap.org/styles/positron'

/** Public URL of the emitted script. */
export const THUMBS_SCRIPT_PATH = '/cities-thumbs.js'

/** Per-city cap on points shipped in `data-points`, to keep the page small. */
export const MAX_THUMB_POINTS = 300

/**
 * `[{lat, lng, category}]` → compact `[[lng, lat, colorHex], …]`, capped at
 * `cap`. Uses the very pins the fallback dots are drawn from (already a
 * deterministic, category-balanced sample), so the map and the fallback agree.
 * Coordinates are rounded to 4 decimals (~11 m), plenty for a 3px dot.
 */
export function samplePoints(pins, cap = MAX_THUMB_POINTS) {
  const out = []
  for (const p of pins) {
    if (out.length >= cap) break
    if (p.lat == null || p.lng == null) continue
    const lat = Number(p.lat)
    const lng = Number(p.lng)
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue
    out.push([
      Number(lng.toFixed(4)),
      Number(lat.toFixed(4)),
      CATEGORY_COLOR[p.category] ?? DEFAULT_PIN_COLOR,
    ])
  }
  return out
}

/** Escape for a single-quoted attribute: `"` stays raw (JSON is full of them). */
const sq = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, '&#39;')

/**
 * Wrap a card's fallback markup in the `.thumb` hook the script upgrades.
 * `bbox` is `{west, south, east, north}`. The attribute is single-quoted so
 * the JSON's double quotes need no escaping (smaller page).
 */
export function wrapThumb({ bbox, points, fallbackHtml }) {
  const bb = [bbox.west, bbox.south, bbox.east, bbox.north].join(',')
  return `<div class="thumb" data-bbox="${bb}" data-points='${sq(JSON.stringify(points))}'>${fallbackHtml}</div>`
}

/** Locate the hashed MapLibre chunk Vite emitted; throws if it is missing. */
export function findMaplibreChunk(assetsDir) {
  let files = []
  try { files = readdirSync(assetsDir) } catch { /* reported below */ }
  const hits = files.filter((f) => /^maplibre-gl-.+\.js$/.test(f)).sort()
  if (!hits.length) {
    throw new Error(
      `no maplibre-gl-*.js chunk in ${assetsDir} — run \`npm run build\` first ` +
      '(the /cities thumbnails import MapLibre from the site\'s own build).',
    )
  }
  return `/assets/${hits[0]}`
}

/** Source of `dist/cities-thumbs.js`. `maplibreChunk` is e.g. `/assets/maplibre-gl-AbC.js`. */
export function renderThumbsScript({ maplibreChunk }) {
  return `// Generated by worker/scripts/lib/citiesThumbs.mjs — do not edit.
// Swaps each /cities card fallback (USGS tiles + dots) for a light-basemap
// MapLibre render, snapshotted to a static <img>. One map is live at a time
// (cards are processed sequentially) so only a single WebGL context exists,
// which keeps iOS Safari and Chrome's context limits out of play.
// Any failure leaves the card's fallback in place.
const STYLE = ${JSON.stringify(THUMB_STYLE_URL)}
const CHUNK = ${JSON.stringify(maplibreChunk)}
let lib = null
const getLib = () => (lib ??= import(CHUNK).then((m) => m.default))

// Render one card; resolves (never rejects) once it is snapshotted or has failed.
function upgrade(thumb, maplibregl) {
  return new Promise((resolve) => {
    const [w, s, e, n] = thumb.dataset.bbox.split(',').map(Number)
    const points = JSON.parse(thumb.dataset.points || '[]')
    const box = document.createElement('div')
    box.className = 'thumb-map'
    box.setAttribute('aria-hidden', 'true')
    box.style.opacity = '0'
    thumb.appendChild(box)
    let map = null
    let finished = false
    const timers = []
    const finish = (img) => {
      if (finished) return
      finished = true
      timers.forEach(clearTimeout)
      try { map && map.remove() } catch {}
      if (img) {
        for (const el of [...thumb.children]) el.remove()
        thumb.appendChild(img)
      } else {
        box.remove()
      }
      resolve()
    }
    try {
      map = new maplibregl.Map({
        container: box,
        style: STYLE,
        bounds: [[w, s], [e, n]],
        fitBoundsOptions: { padding: 6 },
        interactive: false,
        attributionControl: false,
        fadeDuration: 0,
        preserveDrawingBuffer: true,
      })
    } catch {
      finish()
      return
    }
    // A style that never loads (offline, blocked) leaves the fallback visible.
    timers.push(setTimeout(() => finish(), 15000))
    map.on('load', () => {
      if (finished) return
      try {
        map.addSource('pts', {
          type: 'geojson',
          data: {
            type: 'FeatureCollection',
            features: points.map(([lng, lat, c]) => ({
              type: 'Feature', properties: { c }, geometry: { type: 'Point', coordinates: [lng, lat] },
            })),
          },
        })
        map.addLayer({
          id: 'pts', type: 'circle', source: 'pts',
          paint: {
            'circle-radius': 3, 'circle-color': ['get', 'c'],
            'circle-stroke-width': 1, 'circle-stroke-color': '#fff',
          },
        })
      } catch {
        finish()
        return
      }
      // Snapshot once the dots have painted, then free the WebGL context.
      let snapped = false
      const snap = () => {
        if (snapped || finished) return
        snapped = true
        try {
          const img = document.createElement('img')
          img.className = 'thumb-img'
          img.alt = ''
          img.setAttribute('aria-hidden', 'true')
          img.src = map.getCanvas().toDataURL('image/png')
          finish(img)
        } catch {
          finish()
        }
      }
      map.once('idle', snap)
      timers.push(setTimeout(snap, 6000))
    })
  })
}

function hasWebGL() {
  try {
    const c = document.createElement('canvas')
    const gl = c.getContext('webgl2') || c.getContext('webgl')
    gl && gl.getExtension('WEBGL_lose_context') && gl.getExtension('WEBGL_lose_context').loseContext()
    return !!gl
  } catch {
    return false
  }
}

// Cards the IntersectionObserver has declared eligible, processed one at a time.
const queue = []
let running = false
async function drain() {
  if (running) return
  running = true
  try {
    while (queue.length) {
      const thumb = queue.shift()
      try { await upgrade(thumb, await getLib()) } catch {}
    }
  } finally {
    running = false
  }
}

async function start() {
  const thumbs = [...document.querySelectorAll('.thumb[data-bbox]')]
  if (!thumbs.length || !('IntersectionObserver' in window) || !hasWebGL()) return
  const io = new IntersectionObserver((entries) => {
    for (const en of entries) {
      if (!en.isIntersecting) continue
      io.unobserve(en.target)
      queue.push(en.target)
    }
    drain()
  }, { rootMargin: '200px' })
  for (const t of thumbs) io.observe(t)
}

start().catch(() => {})
`
}
